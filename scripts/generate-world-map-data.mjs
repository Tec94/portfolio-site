import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SOURCE_COMMIT = '693f11422f4e08d2da4566b854dda53eb7c39fb3';
const SOURCE_URL =
  `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${SOURCE_COMMIT}` +
  '/geojson/ne_110m_land.geojson';
const OUTPUT_URL = new URL('../src/data/worldMapData.ts', import.meta.url);
const VIEWBOX_WIDTH = 180;
const MAP_HEIGHT = 90;
const SIMPLIFY_TOLERANCE = 0.11;
const GRID_X_STEP = 3.75;
const GRID_Y_STEP = 4;
const GLYPHS = ['.', '.', ':', '+'];

function project([longitude, latitude]) {
  return [(longitude + 180) / 2, (90 - latitude) / 2];
}

function squaredDistanceToSegment(point, start, end) {
  let x = start[0];
  let y = start[1];
  let dx = end[0] - x;
  let dy = end[1] - y;

  if (dx !== 0 || dy !== 0) {
    const progress =
      ((point[0] - x) * dx + (point[1] - y) * dy) / (dx * dx + dy * dy);

    if (progress > 1) {
      x = end[0];
      y = end[1];
    } else if (progress > 0) {
      x += dx * progress;
      y += dy * progress;
    }
  }

  dx = point[0] - x;
  dy = point[1] - y;
  return dx * dx + dy * dy;
}

function simplifySegment(points, first, last, toleranceSquared, simplified) {
  let maximumDistance = toleranceSquared;
  let index = -1;

  for (let pointIndex = first + 1; pointIndex < last; pointIndex += 1) {
    const distance = squaredDistanceToSegment(points[pointIndex], points[first], points[last]);
    if (distance > maximumDistance) {
      index = pointIndex;
      maximumDistance = distance;
    }
  }

  if (index === -1) return;

  if (index - first > 1) {
    simplifySegment(points, first, index, toleranceSquared, simplified);
  }
  simplified.push(points[index]);
  if (last - index > 1) {
    simplifySegment(points, index, last, toleranceSquared, simplified);
  }
}

function simplifyRing(coordinates) {
  const projected = coordinates.map(project);
  const openRing =
    projected.length > 1 &&
    projected[0][0] === projected.at(-1)[0] &&
    projected[0][1] === projected.at(-1)[1]
      ? projected.slice(0, -1)
      : projected;

  if (openRing.length < 4) return openRing;

  const simplified = [openRing[0]];
  simplifySegment(
    openRing,
    0,
    openRing.length - 1,
    SIMPLIFY_TOLERANCE ** 2,
    simplified,
  );
  simplified.push(openRing.at(-1));
  return simplified;
}

function geometryPolygons(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates;
  return [];
}

function pointInRing([x, y], ring) {
  let inside = false;

  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
    const [currentX, currentY] = ring[index];
    const [previousX, previousY] = ring[previous];
    const crosses =
      currentY > y !== previousY > y &&
      x < ((previousX - currentX) * (y - currentY)) / (previousY - currentY) + currentX;

    if (crosses) inside = !inside;
  }

  return inside;
}

function pointInPolygon(point, polygon) {
  return pointInRing(point, polygon[0]) && !polygon.slice(1).some((ring) => pointInRing(point, ring));
}

function formatNumber(value) {
  return Number(value.toFixed(2));
}

function ringToPath(ring) {
  if (ring.length === 0) return '';
  const [first, ...rest] = ring;
  return `M${formatNumber(first[0])} ${formatNumber(first[1])}` +
    rest.map(([x, y]) => `L${formatNumber(x)} ${formatNumber(y)}`).join('') +
    'Z';
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Natural Earth download failed: ${response.status} ${response.statusText}`);
}

const collection = await response.json();
const polygons = collection.features
  .flatMap((feature) => geometryPolygons(feature.geometry))
  .map((polygon) => polygon.map(simplifyRing))
  .filter((polygon) => polygon[0]?.length >= 3);
const worldPath = polygons.flatMap((polygon) => polygon.map(ringToPath)).join('');
const cells = [];

for (let y = 2; y < MAP_HEIGHT - 1; y += GRID_Y_STEP) {
  for (let x = 1.5; x < VIEWBOX_WIDTH - 1; x += GRID_X_STEP) {
    const point = [x, y];
    if (!polygons.some((polygon) => pointInPolygon(point, polygon))) continue;

    const glyphIndex = Math.abs(Math.round(x * 13 + y * 17)) % GLYPHS.length;
    cells.push([formatNumber(x), formatNumber(y), GLYPHS[glyphIndex]]);
  }
}

const output = `/*
 * Generated by scripts/generate-world-map-data.mjs.
 * Source: Natural Earth 1:110m land polygons, public domain.
 * ${SOURCE_URL}
 */

export const WORLD_MAP_PATH = '${worldPath}';

export const WORLD_MAP_CELLS = ${JSON.stringify(cells)} as const;
`;

await writeFile(fileURLToPath(OUTPUT_URL), output, 'utf8');
console.log(
  `Generated ${fileURLToPath(OUTPUT_URL)} with ${polygons.length} polygons and ${cells.length} cells.`,
);
